export async function getContentPage(slug: string): Promise<ContentPageData> {
  try {
    const page = await (prisma as any).contentPage?.findUnique({
      where: { slug },
    });

    if (page) {
      return {
        slug: page.slug,
        title: page.title,
        content: page.content,
        isDraft: page.isDraft,
        updatedAt: page.updatedAt,
        updatedBy: page.updatedBy,
      };
    }
  } catch (err) {
    console.warn(`ContentPage DB fetch error for slug "${slug}", falling back to verified default:`, err);
  }

  const defaultPage = DEFAULT_POLICY_PAGES[slug];
  if (defaultPage) {
    return {
      slug,
      title: defaultPage.title,
      content: defaultPage.content,
      isDraft: defaultPage.isDraft,
    };
  }

  return {
    slug,
    title: 'Policy Details',
    content: 'Policy information is currently being updated. Please contact the showroom at 01753-765372.',
    isDraft: true,
  };
}

export async function updateContentPage(
  slug: string,
  data: { title: string; content: string; isDraft: boolean },
  userId?: string
) {
  const result = await (prisma as any).contentPage.upsert({
    where: { slug },
    update: {
      title: data.title,
      content: data.content,
      isDraft: data.isDraft,
      updatedBy: userId,
    },
    create: {
      slug,
      title: data.title,
      content: data.content,
      isDraft: data.isDraft,
      updatedBy: userId,
    },
  });

  await recordAuditLog({
    userId,
    action: 'POLICY_UPDATE',
    entityType: 'ContentPage',
    entityId: slug,
    details: { title: data.title, isDraft: data.isDraft },
  });

  return result;
}
